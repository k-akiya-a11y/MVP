/**
 * AI に送る前に伏せる（CLAUDE.md 7章）。口座番号・カード番号・電話番号などの長い数字を * にする。
 * 日付や金額は別の項目で渡すので、摘要の中の長い数字は判定に要らない。
 *
 * 対象は下の3つの形式だけ。任意の個人情報（氏名・住所・メールアドレス・海外の番号形式など）を
 * 見つけるものではない。判定に迷う形は、番号に見える側（伏せる側）に倒れうる。
 */
export function maskSensitive(text: string): string {
  const d = "[0-9０-９]";
  return (
    text
      // カード番号（4桁ずつ3〜4グループ。区切りは空白・タブ・改行・NBSP・全角空白の1つ以上）
      .replace(new RegExp(`${d}{4}(?:\\s+${d}{4}){2,3}`, "g"), (m) => "*".repeat(m.length))
      // 括弧区切りの電話番号（例 090(1234)5678、03（1234）5678）。数字は合計7桁以上
      // 先頭は数字の塊の先頭だけ（直前が数字でない）。長い数字の途中から毎回読み直して処理量が2乗になるのを防ぐ。
      // 塊の先頭から一致しなければ途中からも一致しないので、結果は変わらない
      .replace(new RegExp(`(?<!${d})${d}{2,}[(（]${d}{1,4}[)）]${d}{4,}`, "g"), (m) =>
        m.replace(/[^0-9０-９]/g, "").length >= 7 ? "*".repeat(m.length) : m,
      )
      // ハイフン区切りを含む7桁以上の数字
      .replace(new RegExp(`${d}(?:${d}|[-－]){5,}${d}`, "g"), (m) =>
        m.replace(/[-－]/g, "").length >= 7 ? "*".repeat(m.length) : m,
      )
  );
}
